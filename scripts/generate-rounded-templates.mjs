import { readFileSync, writeFileSync } from 'node:fs'
import { buildRoundedSolid } from './lib/rounded-solid-reference.mjs'

// Rounded boxes of every dimension share two topologies. Store the normals,
// triangle indices and core-corner signs once, instead of baking every level.
const templates = [.01, 1].map(radius => {
  const data = buildRoundedSolid([4, 4, 4], radius)
  return {
    corners: data.positions.map((value, i) => Math.round((value - data.normals[i] * radius) / (2 - radius))),
    normals: data.normals.map(value => Number(value.toFixed(15))),
    indices: data.indices,
  }
})
const file = new URL('../shared/generated/rounded-templates.js', import.meta.url)
const source = '// Generated by pnpm generate:game-geometry. Do not edit by hand.\nexport const roundedTemplates = ' + JSON.stringify(templates) + '\n'
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== source) throw new Error('Stale rounded templates: run pnpm generate:game-geometry')
} else writeFileSync(file, source)
